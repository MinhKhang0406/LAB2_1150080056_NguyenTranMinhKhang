    private void btn_encryptActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_encryptActionPerformed
        String plaintext = txt_plaintext.getText();
    if (plaintext.isEmpty()) { JOptionPane.showMessageDialog(this, "Hãy nhập Plaintext trước khi mã hóa.");
    return;
    }
    try {
    String ciphertext = DESCipher.encrypt(plaintext, txt_key.getText());
        txt_ciphertext.setText(ciphertext);
         lbl_status.setText("<html>Đã mã hóa DES. " + HistoryDao.tryInsert("DES", "ENCRYPT", null,
    plaintext.length(), ciphertext.length()) + "</html>"); } catch (IllegalArgumentException ex) { JOptionPane.showMessageDialog(this, ex.getMessage(), "Dữ liệu không hợp lệ", JOptionPane.ERROR_MESSAGE);
    } catch (Exception ex) {
     JOptionPane.showMessageDialog(this, "Mã hóa thất bại:\n" + ex.getMessage(), "Lỗi", JOptionPane.ERROR_MESSAGE);
     }

    }//GEN-LAST:event_btn_encryptActionPerformed

